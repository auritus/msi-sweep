namespace MsiSweep.Output;

/// <summary>
/// Specifies the alignment of the cell text in a table column.
/// </summary>
public enum ColumnAlignment
{
    /// <summary>
    /// The cell text is aligned to the left edge of the column.
    /// </summary>
    Left,

    /// <summary>
    /// The cell text is aligned to the right edge of the column.
    /// </summary>
    Right
}
